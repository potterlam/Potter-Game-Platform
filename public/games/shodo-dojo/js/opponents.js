// 隨機揀一句對白
function getDialogue(level, category) {
  const key = level === 'custom' ? 'level1' : level;
  const opponent = OPPONENTS[key];
  if (!opponent || !opponent.dialogues[category]) return '';
  const lines = opponent.dialogues[category];
  return lines[Math.floor(Math.random() * lines.length)];
}
